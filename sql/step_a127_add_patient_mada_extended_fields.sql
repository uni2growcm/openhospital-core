ALTER TABLE OH_PATIENT ADD COLUMN PAT_CHILDREN_NUMBER int(11) DEFAULT 0 AFTER PAT_GEOGRAPHIC_AREA;
ALTER TABLE OH_PATIENT ADD COLUMN PAT_PARENT_RESIDENCE varchar(50) DEFAULT NULL AFTER PAT_CHILDREN_NUMBER;
ALTER TABLE OH_PATIENT ADD COLUMN PAT_TRANSPORT varchar(254) DEFAULT NULL AFTER PAT_PARENT_RESIDENCE;
ALTER TABLE OH_PATIENT ADD COLUMN PAT_BLAMA varchar(40) DEFAULT NULL AFTER PAT_TRANSPORT;
ALTER TABLE OH_PATIENT ADD COLUMN PAT_COUNTRY varchar(30) DEFAULT NULL AFTER PAT_BLAMA;
ALTER TABLE OH_PATIENT ADD COLUMN PAT_AFFILIATED_PERSON int(11) DEFAULT NULL AFTER PAT_COUNTRY;
