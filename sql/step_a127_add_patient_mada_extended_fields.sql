--
-- Extended patient demographics and administrative fields ported from oh-mada-gui's
-- PatientInsertExtended: birth place, geographic area, household details, transport, a
-- client-required "Blama" field, a country lookup with an inline create dialog, an
-- employee/head-of-household affiliation link, and a price-list assignment.
--

CREATE TABLE OH_COUNTRY (
	CTR_ID int(11) NOT NULL AUTO_INCREMENT,
	CTR_CODE varchar(20) DEFAULT NULL,
	CTR_NAME varchar(50) NOT NULL,
	CTR_PHONE_CODE varchar(10) DEFAULT NULL,
	CTR_LOCK int(11) NOT NULL DEFAULT 0,
	CTR_CREATED_BY varchar(50) DEFAULT NULL,
	CTR_CREATED_DATE datetime DEFAULT NULL,
	CTR_LAST_MODIFIED_BY varchar(50) DEFAULT NULL,
	CTR_LAST_MODIFIED_DATE datetime DEFAULT NULL,
	CTR_ACTIVE tinyint(1) NOT NULL DEFAULT 1,
	PRIMARY KEY (CTR_ID)
) ENGINE=InnoDB;

