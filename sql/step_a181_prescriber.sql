CREATE TABLE IF NOT EXISTS OH_PRESCRIBER (
    PRS_ID                  INT AUTO_INCREMENT PRIMARY KEY,
    PRS_NAME                VARCHAR(100) NOT NULL,
    PRS_CREATED_BY          VARCHAR(50)  DEFAULT NULL,
    PRS_CREATED_DATE        DATETIME     DEFAULT NULL,
    PRS_LAST_MODIFIED_BY    VARCHAR(50)  DEFAULT NULL,
    PRS_LAST_MODIFIED_DATE  DATETIME     DEFAULT NULL,
    PRS_ACTIVE              TINYINT(1)   NOT NULL DEFAULT 1,
    PRS_LOCK                INT          NOT NULL DEFAULT 0,
    INDEX idx_prescriber_name (PRS_NAME)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

